// App rules that would reach into the scenes from Help's own surroundings:
// the Settings dialog Help is shown in. A scene draws other windows, so the
// dialog's descendant rules must not style it (see the :where(:not(.help-figure *))
// guards in the app's stylesheet).
// Interaction-only rules (focus rings, hover) are left out: a scene is a picture.
const HELP_ANCESTOR = /\.(?:modal-backdrop|pzza-portal|settings-hub-backdrop|modal|settings-hub|settings-hub-layout|settings-hub-main|help-hub-content|help-article|help-prose|help-figure)(?![\w-])/;
const INTERACTION = /:(?:focus|focus-visible|focus-within|hover|active)(?![\w-])/;
/** A selector's compounds, each with the combinator after it (" ", ">", "+", "~" or null). */
function compounds(selector) {
  const parts = [];
  let current = "";
  let depth = 0;
  for (let index = 0; index < selector.length; index++) {
    const char = selector[index];
    if (char === "(" || char === "[") depth++;
    if (char === ")" || char === "]") depth--;
    if (depth === 0 && /[\s>+~]/.test(char)) {
      let combinator = " ";
      while (index < selector.length && /[\s>+~]/.test(selector[index])) {
        if (!/\s/.test(selector[index])) combinator = selector[index];
        index++;
      }
      index--;
      if (current) parts.push({ compound: current, next: combinator });
      current = "";
      continue;
    }
    current += char;
  }
  if (current) parts.push({ compound: current, next: null });
  return parts;
}
const reachesScenes = (selector) => {
  const parts = compounds(selector);
  if (INTERACTION.test(parts.at(-1)?.compound ?? "")) return false;
  // Scenes sit many levels below the dialog: from one of its containers, a
  // descendant combinator reaches them, a chain of child combinators only
  // while it runs through Help's own containers, a sibling combinator never.
  return parts.some((part, index) => {
    if (index === parts.length - 1 || !HELP_ANCESTOR.test(part.compound)) return false;
    for (let step = index; step < parts.length - 1; step++) {
      if (parts[step].next === " ") return true;
      if (parts[step].next !== ">" || !HELP_ANCESTOR.test(parts[step + 1].compound)) return false;
    }
    return false;
  });
};
for (const file of appCss) {
  postcss.parse(read(file)).walkRules((rule) => {
    for (const selector of rule.selectors) {
      // The guarded form: outside the figures, or inside a dialog a scene draws.
      if (selector.includes(":not(.help-figure *)") || selector.startsWith(":where(.help-figure)") || !reachesScenes(selector)) continue;
      warnings.push(`${toPosix(relative(app, file))}:${rule.source.start.line} "${selector}" can style Help's scenes from the Settings dialog`);
    }
  });
}

