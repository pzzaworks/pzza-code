#!/usr/bin/env node
/**
 * Writes src/help/generated/ from the website (pzza-code-web), so the in-app
 * Help shows the docs themselves: the same pages, prose and product scenes,
 * from one source.
 *
 * - pages: every docs page (content/docs/(section)/*.mdx, in the order of the
 *   sections' meta.json), compiled with the docs' own MDX compiler and GFM to
 *   plain JS modules (pages/<slug>.js, typed by pages/<slug>.d.ts), with their
 *   frontmatter and nav labels in docs.ts
 * - scenes: the scene entries of the docs' MDX component map
 *   (components/DocsMdx.tsx: `Tag: scene(Shot)` and the area registries it
 *   spreads) in scenes.tsx, plus every file they import under kit/, at the
 *   web's own paths. The only changes are mechanical: `@/` imports become
 *   relative, `next/image` resolves to a plain <img> shim and "use client" is
 *   dropped. Images and CSS the scenes import are copied as they are.
 * - CSS: the scene kit rules of components/home/home.css (the window frame,
 *   the terminal screen, wrappers, the tooltip host and the media overrides,
 *   not the page layout) and components/home/scene-loops.css in
 *   kit/scene-kit.css. The web's app.css is not copied: inside the app the
 *   app's own stylesheet styles the scenes, with the user's theme.
 *   kit/viewport.css restates the app's viewport-unit rules inside scenes
 *   against the scene window's --pz-vh / --pz-vw, as the web's app.css does.
 *
 * Everything under src/help/generated/ is replaced on every run, so edit the
 * website (or this script), never the output.
 *
 * Usage: npm run sync:help [-- <path to the pzza-code-web checkout>]
 * (defaults to ../pzza-code-web next to this repository).
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, extname, join, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const web = resolve(process.argv[2] ?? resolve(app, "../pzza-code-web"));
const out = join(app, "src/help/generated");
const kitOut = join(out, "kit");

if (!existsSync(join(web, "content/docs/meta.json"))) throw new Error(`No docs found at ${web}: pass the pzza-code-web checkout as the first argument.`);

// The website's toolchain compiles its own pages and parses its CSS; the app's
// TypeScript scans imports. Nothing is added to the app's dependencies.
const webRequire = createRequire(join(web, "package.json"));
const appRequire = createRequire(join(app, "package.json"));
const webImport = async (name) => import(pathToFileURL(webRequire.resolve(name)).href);
const { compile, createProcessor } = await webImport("@mdx-js/mdx");
const { default: remarkGfm } = await webImport("remark-gfm");
const matter = webRequire("gray-matter");
const postcss = webRequire("postcss");
const ts = appRequire("typescript");

const toPosix = (path) => path.split(sep).join("/");
/** A path inside the website, as the generated files name their source. */
const webPath = (file) => toPosix(relative(web, file));
const read = (file) => readFileSync(file, "utf8");
const write = (file, text) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};
const generatedFrom = (source) => `Generated by scripts/sync-help.mjs from pzza-code-web/${source}. Regenerate with \`npm run sync:help\` rather than editing.`;
const jsHeader = (source) => `// ${generatedFrom(source)}\n`;
const cssHeader = (source) => `/* ${generatedFrom(source)} */\n`;

rmSync(out, { recursive: true, force: true });
const warnings = [];

/* ================================================================ pages == */

const docsDir = join(web, "content/docs");
const readJson = (file) => JSON.parse(read(file));
const sections = [];
for (const folder of readJson(join(docsDir, "meta.json")).pages) {
  const id = /^\((.+)\)$/.exec(folder)?.[1];
  if (!id) throw new Error(`Unexpected docs section "${folder}" in content/docs/meta.json`);
  const meta = readJson(join(docsDir, folder, "meta.json"));
  const pages = [];
  for (const entry of meta.pages) {
    if (entry.startsWith("!")) continue; // listed through a link entry
    const link = /^\[(.+)\]\(\/docs\/([\w-]+)\)$/.exec(entry);
    const slug = link ? link[2] : entry;
    if (!/^[\w-]+$/.test(slug)) throw new Error(`Unexpected page entry "${entry}" in ${folder}/meta.json`);
    const file = join(docsDir, folder, `${slug}.mdx`);
    if (!existsSync(file)) throw new Error(`${folder}/meta.json lists "${slug}", which has no ${slug}.mdx`);
    pages.push({ slug, nav: link?.[1], file });
  }
  const listed = new Set(pages.map((page) => page.slug));
  for (const file of readdirSync(join(docsDir, folder))) {
    if (file.endsWith(".mdx") && !listed.has(file.slice(0, -4))) warnings.push(`content/docs/${folder}/${file} is not listed in its meta.json, so Help leaves it out`);
  }
  sections.push({ id, title: meta.title, pages });
}
const allPages = sections.flatMap((section) => section.pages);
const slugs = new Set(allPages.map((page) => page.slug));

/** Every JSX tag and every link target in a page's MDX tree. */
function scan(tree) {
  const tags = new Set();
  const links = new Set();
  const walk = (node) => {
    if ((node.type === "mdxJsxFlowElement" || node.type === "mdxJsxTextElement") && node.name) tags.add(node.name);
    if (node.type === "link") links.add(node.url);
    for (const child of node.children ?? []) walk(child);
  };
  walk(tree);
  return { tags, links };
}

const parser = createProcessor({ remarkPlugins: [remarkGfm] });
const usedTags = new Map();
for (const page of allPages) {
  const { content, data } = matter(read(page.file));
  if (typeof data.title !== "string" || !data.title) throw new Error(`${webPath(page.file)} has no title in its frontmatter`);
  page.title = data.title;
  page.description = typeof data.description === "string" ? data.description : "";
  const { tags, links } = scan(parser.parse(content));
  for (const tag of tags) usedTags.set(tag, [...(usedTags.get(tag) ?? []), page.slug]);
  for (const link of links) {
    const target = /^\/docs(?:\/([\w-]+))?(?:#.*)?$/.exec(link);
    if (target && !slugs.has(target[1] ?? "index")) throw new Error(`${webPath(page.file)} links to ${link}, which is not a docs page`);
  }
  // The docs' compiler (pzzadocs: @mdx-js/mdx with GFM) to a plain module; the
  // components come in through the `components` prop, as on the website.
  const compiled = await compile(content, { outputFormat: "program", remarkPlugins: [remarkGfm], development: false });
  write(join(out, "pages", `${page.slug}.js`), jsHeader(webPath(page.file)) + String(compiled));
  write(join(out, "pages", `${page.slug}.d.ts`), `${jsHeader(webPath(page.file))}import type { MdxContent } from "../mdx";\n\ndeclare const content: MdxContent;\nexport default content;\n`);
}

const siteUrl = /export const SITE_URL = "(https:\/\/[^"]+)";/.exec(read(join(web, "lib/seo.ts")))?.[1];
if (!siteUrl) throw new Error("SITE_URL not found in lib/seo.ts");

const quote = (value) => JSON.stringify(value);
write(join(out, "docs.ts"), `${jsHeader("content/docs")}
/** The website the docs are published on; links outside the docs open there. */
export const DOCS_SITE = ${quote(siteUrl)};

/** The docs' sections in reading order, as their meta.json lists them. */
export const DOCS_SECTIONS = [
${sections.map((section) => `  { id: ${quote(section.id)}, title: ${quote(section.title)}, pages: [${section.pages.map((page) => quote(page.slug)).join(", ")}] },`).join("\n")}
] as const;

export type DocSlug = typeof DOCS_SECTIONS[number]["pages"][number];

export interface DocMeta {
  /** The page heading, from the frontmatter. */
  title: string;
  /** The line under the heading, from the frontmatter. */
  description: string;
  /** The shorter label the docs' navigation shows, when the section gives one. */
  nav?: string;
}

/** Every page's frontmatter, by its docs slug (/docs/<slug>; the overview is "index"). */
export const DOCS_PAGES: Record<DocSlug, DocMeta> = {
${allPages.map((page) => `  ${quote(page.slug)}: { title: ${quote(page.title)}, description: ${quote(page.description)}${page.nav ? `, nav: ${quote(page.nav)}` : ""} },`).join("\n")}
};
`);

write(join(out, "mdx.ts"), `${jsHeader("content/docs")}
import type { ComponentType, ReactElement } from "react";

/**
 * The components a page renders its tags with, by tag name: HTML elements
 * (\`a\`, \`h2\`, \`table\`) and the docs' own components (\`Kbd\`, the scenes).
 * MDX hands each one the props the page writes, so any component fits.
 */
export type MdxComponents = Readonly<Record<string, ComponentType<never>>>;

/** A compiled docs page. */
export type MdxContent = (props: { components?: MdxComponents }) => ReactElement;
`);

write(join(out, "content.ts"), `${jsHeader("content/docs")}
import type { DocSlug } from "./docs";
import type { MdxContent } from "./mdx";
${allPages.map((page, index) => `import page${index} from "./pages/${page.slug}.js";`).join("\n")}

/** Every page's compiled content, by its docs slug. */
export const DOCS_CONTENT: Record<DocSlug, MdxContent> = {
${allPages.map((page, index) => `  ${quote(page.slug)}: page${index},`).join("\n")}
};
`);

/* =============================================================== scenes == */

// The tags the app renders itself (src/panels/HelpModal.tsx): the docs'
// non-scene components, in the app's own markup.
const APP_TAGS = new Set(["Kbd", "Callout", "ShortcutTable"]);

const docsMdxFile = join(web, "components/DocsMdx.tsx");
const docsMdx = read(docsMdxFile);
const imports = new Map();
for (const [, names, from] of docsMdx.matchAll(/import\s*\{([^}]*)\}\s*from\s*"([^"]+)";/g)) {
  for (const name of names.split(",").map((item) => item.trim()).filter(Boolean)) {
    const [imported, local = imported] = name.replace(/^type\s+/, "").split(/\s+as\s+/);
    imports.set(local, { imported, from });
  }
}
const mapBody = /export const docsComponents = \{([\s\S]*?)\n\};/.exec(docsMdx)?.[1];
if (!mapBody) throw new Error("docsComponents not found in components/DocsMdx.tsx");
const sceneEntries = [];
const spreads = [];
for (const line of mapBody.split("\n").map((item) => item.trim())) {
  const entry = /^(\w+): scene\((\w+)\),?$/.exec(line);
  if (entry) sceneEntries.push({ tag: entry[1], shot: entry[2] });
  const spread = /^\.\.\.(\w+),?$/.exec(line);
  if (spread) spreads.push(spread[1]);
}
// The small shots DocsMdx defines itself (menu bar dropdowns with no card of their own).
const localShots = new Map([...docsMdx.matchAll(/^function (\w+)\(\) \{\n[\s\S]*?\n\}$/gm)].map((match) => [match[1], match[0]]));

/** The tags a registry module (components/docs/*Scenes.tsx) registers. */
function registryTags(file) {
  const body = /export const \w+: Record<string, ComponentType> = \{([\s\S]*?)\n\};/.exec(read(file))?.[1];
  if (!body) throw new Error(`No scene registry object in ${webPath(file)}`);
  return [...body.matchAll(/^\s*(\w+):/gm)].map((match) => match[1]);
}

const resolveAlias = (specifier) => (specifier.startsWith("@/") ? join(web, specifier.slice(2)) : null);
const SOURCE_EXTENSIONS = [".tsx", ".ts", ".jsx", ".js"];
function resolveFile(base) {
  if (existsSync(base) && statSync(base).isFile()) return base;
  for (const ext of SOURCE_EXTENSIONS) if (existsSync(base + ext)) return base + ext;
  for (const ext of SOURCE_EXTENSIONS) if (existsSync(join(base, `index${ext}`))) return join(base, `index${ext}`);
  return null;
}

const used = new Set(usedTags.keys());
const sceneTags = new Set();
const entryImports = new Map();
const needImport = (local) => {
  const origin = imports.get(local);
  if (!origin) throw new Error(`${local} is used by docsComponents but not imported in components/DocsMdx.tsx`);
  const file = resolveFile(resolveAlias(origin.from) ?? "");
  if (!file) throw new Error(`Cannot resolve ${origin.from} from components/DocsMdx.tsx`);
  entryImports.set(local, { imported: origin.imported, file });
};
needImport("scene");
const keptLocalShots = [];
for (const { tag, shot } of sceneEntries) {
  sceneTags.add(tag);
  if (localShots.has(shot)) {
    keptLocalShots.push(localShots.get(shot));
    for (const [, name] of localShots.get(shot).matchAll(/<(\w+)/g)) needImport(name);
  } else needImport(shot);
}
for (const registry of spreads) {
  needImport(registry);
  for (const tag of registryTags(entryImports.get(registry).file)) sceneTags.add(tag);
}
const missing = [...used].filter((tag) => /^[A-Z]/.test(tag) && !sceneTags.has(tag) && !APP_TAGS.has(tag));
if (missing.length) {
  throw new Error(`Docs pages use tags Help has no component for:\n${missing.map((tag) => `  <${tag} /> (${usedTags.get(tag).join(", ")})`).join("\n")}\nRegister a scene for them in the website's DocsMdx.tsx or a *Scenes.tsx registry, or render them in src/panels/HelpModal.tsx and list them in APP_TAGS.`);
}

/* ------------------------------------------------------------ kit files -- */

const appPackage = readJson(join(app, "package.json"));
const appPackages = new Set(Object.keys({ ...appPackage.dependencies, ...appPackage.devDependencies }));
const kitPath = (file) => join(kitOut, relative(web, file));
const NEXT_IMAGE_SHIM = join(kitOut, "next-image.tsx");
const copied = new Set();
const queue = [...new Set([...entryImports.values()].map((item) => item.file))];
let shimNeeded = false;

function bareAllowed(specifier) {
  const name = specifier.startsWith("@") ? specifier.split("/").slice(0, 2).join("/") : specifier.split("/")[0];
  return appPackages.has(name);
}

while (queue.length) {
  const file = queue.shift();
  if (copied.has(file)) continue;
  copied.add(file);
  const ext = extname(file);
  const target = kitPath(file);
  if (!SOURCE_EXTENSIONS.includes(ext)) {
    if (ext === ".css") write(target, cssHeader(webPath(file)) + read(file));
    else {
      mkdirSync(dirname(target), { recursive: true });
      copyFileSync(file, target);
    }
    continue;
  }
  let source = read(file);
  // Module directives mean nothing to Vite, which warns about every one.
  source = source.replace(/^(["'])use client\1;?\r?\n(\r?\n)?/, "");
  // Types only: React 19's RefObject<T | null> is React 18's RefObject<T>
  // (whose current is already T | null), the form the app's React accepts as a ref.
  source = source.replace(/\bRefObject<([^<>]+?) \| null>/g, "RefObject<$1>");
  // ts.preProcessFile reads real import statements only, never the sample
  // code the scenes keep in template strings.
  const edits = [];
  for (const ref of ts.preProcessFile(source, true, true).importedFiles) {
    const specifier = ref.fileName;
    let resolved = null;
    if (specifier === "next/image") {
      shimNeeded = true;
      edits.push({ pos: ref.pos, end: ref.end, text: relativeSpecifier(target, NEXT_IMAGE_SHIM) });
      continue;
    }
    if (specifier.startsWith("@/")) resolved = resolveAlias(specifier);
    else if (specifier.startsWith(".")) resolved = join(dirname(file), specifier);
    else if (bareAllowed(specifier)) continue;
    else throw new Error(`${webPath(file)} imports "${specifier}", which the app does not have`);
    const dependency = resolveFile(resolved);
    if (!dependency) throw new Error(`${webPath(file)} imports "${specifier}", which does not resolve`);
    if (!dependency.startsWith(join(web, "components") + sep)) throw new Error(`${webPath(file)} imports ${webPath(dependency)}, outside components/`);
    queue.push(dependency);
    if (specifier.startsWith("@/")) edits.push({ pos: ref.pos, end: ref.end, text: relativeSpecifier(target, kitPath(resolveFile(resolved))) });
  }
  // A reference's pos is its string literal's opening quote; the edit swaps the whole literal.
  for (const edit of edits.sort((a, b) => b.pos - a.pos)) {
    const quoteChar = source[edit.pos];
    const close = source.indexOf(quoteChar, edit.pos + 1);
    if (!/["']/.test(quoteChar) || close < 0) throw new Error(`Cannot rewrite an import in ${webPath(file)} at ${edit.pos}`);
    source = source.slice(0, edit.pos) + JSON.stringify(edit.text) + source.slice(close + 1);
  }
  write(target, jsHeader(webPath(file)) + source);
}

function relativeSpecifier(fromFile, toFile) {
  let path = toPosix(relative(dirname(fromFile), toFile)).replace(/\.(tsx|ts|jsx|js)$/, "");
  if (!path.startsWith(".")) path = `./${path}`;
  return path;
}

if (shimNeeded) {
  write(NEXT_IMAGE_SHIM, `${jsHeader("components/home/Backdrop.tsx (its next/image)")}
import type { CSSProperties } from "react";

/** A bundled image: Vite imports an image as its URL. */
export type StaticImageData = string;

interface ImageProps {
  src: StaticImageData;
  alt: string;
  /** Fill the positioned parent, as next/image's \`fill\` does. */
  fill?: boolean;
  /** next/image's loading hints; a plain image has no blur placeholder. */
  placeholder?: "blur" | "empty";
  priority?: boolean;
  style?: CSSProperties;
  className?: string;
}

/** next/image as a plain <img>: the scenes' wallpapers are already sized and compressed. */
export default function Image({ src, alt, fill, priority, style, className }: ImageProps) {
  const fillStyle: CSSProperties | undefined = fill ? { position: "absolute", inset: 0, width: "100%", height: "100%" } : undefined;
  return <img src={src} alt={alt} className={className} decoding="async" loading={priority ? "eager" : "lazy"} style={{ ...fillStyle, ...style }} />;
}
`);
}

/* ---------------------------------------------------------- scene map --- */

const kitImport = (file) => relativeSpecifier(join(out, "scenes.tsx"), kitPath(file));
const byFile = new Map();
for (const [local, { imported, file }] of entryImports) {
  const names = byFile.get(file) ?? [];
  names.push(imported === local ? local : `${imported} as ${local}`);
  byFile.set(file, names);
}
write(join(out, "scenes.tsx"), `${jsHeader(`components/DocsMdx.tsx (its scene entries)`)}
import type { ComponentType } from "react";
${[...byFile].map(([file, names]) => `import { ${names.sort().join(", ")} } from "${kitImport(file)}";`).join("\n")}
import "./app-styles";
import "./kit/scene-kit.css";
import "./kit/viewport.css";

/** The agents' marks the scenes point at: the docs layout renders it once per page (app/docs/layout.tsx). */
export { AgentMarkSprite } from "${kitImport(join(web, "components/home/AppUI.tsx"))}";

${keptLocalShots.join("\n")}

/** The docs pages' product scenes, by the tag their MDX uses (as in DocsMdx.tsx). */
export const DOCS_SCENES: Record<string, ComponentType> = {
${sceneEntries.map(({ tag, shot }) => `  ${tag}: scene(${shot}),`).join("\n")}
${spreads.map((registry) => `  ...${registry},`).join("\n")}
};
`);

// What the docs layout mounts around every page: Help renders the mark
// sprite itself, and the app's own Tooltip stands in for SceneTooltip.
const docsLayout = read(join(web, "app/docs/layout.tsx"));
for (const [, name] of docsLayout.matchAll(/<(\w+) \/>/g)) {
  if (!["AgentMarkSprite", "SceneTooltip"].includes(name)) warnings.push(`app/docs/layout.tsx renders <${name} />, which Help does not`);
}
if (!docsLayout.includes("<AgentMarkSprite />")) warnings.push("app/docs/layout.tsx no longer renders <AgentMarkSprite />; check whether Help still needs it");

/* ================================================================== CSS == */

// home.css: only the rules that draw the scenes (their selectors start at the
// card, .h-visual, or the scene root, .pz), with the at-rules around them, the
// keyframes they run and their cascade layer. Page layout (.home, .h-*) stays out.
const KIT_SELECTOR = /^(?::where\()?\.(?:pz(?:-[\w-]+)?|h-visual)(?![\w-])/;
const homeFile = join(web, "components/home/home.css");
const home = postcss.parse(read(homeFile));
const kit = postcss.root();
const keyframesUsed = new Set();
function keepRules(container, into) {
  container.each((node) => {
    if (node.type === "rule") {
      if (!node.selectors.every((selector) => KIT_SELECTOR.test(selector.trim()))) return;
      const clone = node.clone();
      clone.walkDecls(/^animation(-name)?$/, (decl) => decl.value.split(/[\s,]+/).forEach((word) => keyframesUsed.add(word)));
      into.append(clone);
    } else if (node.type === "atrule" && /keyframes$/.test(node.name)) {
      into.append(node.clone());
    } else if (node.type === "atrule" && node.nodes) {
      const wrapper = node.clone({ nodes: [] });
      keepRules(node, wrapper);
      if (wrapper.nodes.length) into.append(wrapper);
    }
  });
}
keepRules(home, kit);
kit.walkAtRules(/keyframes$/, (rule) => {
  if (!keyframesUsed.has(rule.params)) rule.remove();
});
kit.walkComments((comment) => comment.remove());
const loopsFile = join(web, "components/home/scene-loops.css");
write(join(kitOut, "scene-kit.css"), `${cssHeader(`${webPath(homeFile)} (its scene rules) and ${webPath(loopsFile)}`)}${kit.toString().trim()}\n\n${read(loopsFile).trim()}\n`);

// The app's viewport units inside a scene: the web's copy of the app's
// stylesheet reads them from --pz-vh / --pz-vw, which a scene sets to its
// window's size; here the app's rules read the app's real window. Each rule
// with viewport units is restated for scene content against those variables
// (1vh / 1vw where a scene sets none).
const VIEWPORT = /(-?\d*\.?\d+)(?:d|s|l)?v(h|w)\b/g;
const ROOT_COMPOUND = /^((?::root|html)(?:\[[^\]]*\]|\.[\w-]+|:not\([^)]*\))*(?:\s+body(?:\[[^\]]*\]|\.[\w-]+)*)?)(\s+|$)/;
const scopeToScene = (selector) => {
  const root = ROOT_COMPOUND.exec(selector);
  if (!root) return `.pz ${selector}`;
  const rest = selector.slice(root[0].length);
  return rest ? `${root[1]} .pz ${rest}` : null; // the document itself is never inside a scene
};
const appCss = [];
const walkCss = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (path === out) continue;
    if (statSync(path).isDirectory()) walkCss(path);
    else if (name.endsWith(".css")) appCss.push(path);
  }
};
walkCss(join(app, "src"));
const viewport = postcss.root();
for (const file of appCss.sort()) {
  postcss.parse(read(file)).walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    const decls = [];
    rule.each((node) => {
      if (node.type === "decl" && !node.prop.startsWith("--") && VIEWPORT.test(node.value)) decls.push(node);
      VIEWPORT.lastIndex = 0;
    });
    if (!decls.length) return;
    const selectors = rule.selectors.map((selector) => scopeToScene(selector.trim())).filter(Boolean);
    if (!selectors.length) return;
    let node = postcss.rule({ selectors });
    for (const decl of decls) {
      node.append(decl.clone({ value: decl.value.replace(VIEWPORT, (_, n, axis) => `calc(${n} * var(--pz-v${axis}, 1v${axis}))`) }));
    }
    for (let parent = rule.parent; parent && parent.type === "atrule"; parent = parent.parent) {
      const wrapper = parent.clone({ nodes: [] });
      wrapper.append(node);
      node = wrapper;
    }
    viewport.append(node);
  });
}
// Every stylesheet of the app, as the website's app.css holds all of them: a
// scene draws panels whose styles the app otherwise loads only with their
// own code (the editor's, for one). Those already in the app's main
// stylesheet stay there; Vite adds the rest to Help's.
write(join(out, "app-styles.ts"), `// Generated by scripts/sync-help.mjs from the app's own stylesheets under src/. Regenerate with \`npm run sync:help\` rather than editing.
// Every app stylesheet, so the scenes find the styles of panels that are not open.
${appCss.map((file) => `import "${relativeSpecifier(join(out, "app-styles.ts"), file)}";`).join("\n")}
`);
write(join(kitOut, "viewport.css"), `/* Generated by scripts/sync-help.mjs from the app's own stylesheets under src/: their viewport-unit rules restated for scene content, as the website's app.css reads them. Regenerate with \`npm run sync:help\` rather than editing. */\n${viewport.toString().trim()}\n`);

